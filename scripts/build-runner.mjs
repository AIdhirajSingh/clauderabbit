#!/usr/bin/env node
/**
 * Bundle the scan runner (lib/server/runner-main.ts) into one ESM file for Node 24 and
 * wrap it as lib/server/runner-bundle.generated.mjs (default export: the code), which
 * lib/server/runner.ts uploads to each runner sandbox. Run by `build` and `vercel-build`
 * before `next build`. The bundle holds code only, never a key.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tmp = mkdtempSync(path.join(tmpdir(), "cr-runner-"));
const out = path.join(tmp, "runner.mjs");
execFileSync("npx", ["-y", "esbuild@0.25.10", "lib/server/runner-main.ts", "--bundle", "--platform=node", "--format=esm", "--target=node24",
  `--outfile=${out}`, "--log-level=warning", "--banner:js=import { createRequire as __crRequire } from 'node:module'; const require = __crRequire(import.meta.url);"],
  { cwd: ROOT, stdio: "inherit" });
const code = readFileSync(out, "utf8");
writeFileSync(path.join(ROOT, "lib/server/runner-bundle.generated.mjs"), `// Generated by scripts/build-runner.mjs. Do not edit.\nexport default ${JSON.stringify(code)};\n`);
rmSync(tmp, { recursive: true, force: true });
console.log(`[cr-runner] bundled ${code.length} bytes`);
